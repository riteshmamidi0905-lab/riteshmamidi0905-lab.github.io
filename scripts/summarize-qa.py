"""Write docs/redesign/QA-AND-PERFORMANCE.md from docs/redesign/qa-results.json and docs/redesign/lighthouse/*.json (measured, not hand-typed)."""
import json, glob
q = json.load(open("docs/redesign/qa-results.json"))
rows = []
for f in sorted(glob.glob("docs/redesign/lighthouse/*.json")):
    d = json.load(open(f)); c = d["categories"]; a = d["audits"]
    rows.append(f"| {f.split('/')[-1][:-5]} | " + " | ".join(str(round(c[k]['score'] * 100)) if k in c else '—' for k in ('performance', 'accessibility', 'best-practices', 'seo')) +
                f" | {a['largest-contentful-paint']['displayValue'].replace(chr(160),' ')} | {a['cumulative-layout-shift']['displayValue']} | {a['total-blocking-time']['displayValue'].replace(chr(160),' ')} | {round(a['total-byte-weight']['numericValue']/1024)} KB |")
m = q["metrics"]
mrows = [f"| {k} | {v['lcp_ms']} ms | {v['cls']} | {v['load_ms']} ms | {round(v['js_bytes']/1024,1)} KB | {round(v['css_bytes']/1024,1)} KB |" for k, v in m.items()]
fails = q["summary"]["failed"]
out = f"""# QA and performance results (generated; D-90 candidate)
Generated by `scripts/summarize-qa.py` from `scripts/qa-redesign.py` and Lighthouse JSON in `docs/redesign/lighthouse/`. **Environment:** local `python3 -m http.server` (no compression, no CDN), headless Chromium 1194 on the build machine; Lighthouse default simulated throttling. Real GitHub Pages numbers will differ (it compresses and caches).

## Automated browser checks: {q['summary']['passed']}/{q['summary']['checks']} passed
Pages: index, nasha, recruiter · viewports 1440, 1280, 820, 390 and 320 px · checks: no horizontal overflow, **no element extending past the viewport edge** (added after a mobile defect that `scrollWidth` could not see), no clipped text, standalone touch targets ≥ 36 px, axe-core WCAG 2 A/AA + best-practice (serious/critical = 0, desktop and mobile), no console errors or failed requests, keyboard operation (tab arrows, Home/End, Enter on controls, skip link, architecture nodes), reduced motion, slow-network metrics, JS ≤ 40 KB and CSS ≤ 30 KB.
Failed checks: {'none' if not fails else [f['check'] for f in fails]}

## Slow-network profile (mobile 390×844, 150 ms RTT, 1.6 Mbps, 4× CPU slowdown, emulated)
| Page | LCP | CLS | Load | JS | CSS |
|---|---|---|---|---|---|
""" + "\n".join(mrows) + """

## Lighthouse (performance / accessibility / best practices / SEO)
| Run | Perf | A11y | BP | SEO | LCP | CLS | TBT | Transfer |
|---|---|---|---|---|---|---|---|---|
""" + "\n".join(rows) + """

## Targets and what they mean
LCP ≤ 2.5 s, CLS ≤ 0.1, JS ≤ 40 KB, CSS ≤ 30 KB, axe serious/critical = 0, Lighthouse mobile performance ≥ 90. These are the project's own thresholds (reported Awwwards-winner benchmarks are secondary-source hearsay, see DESIGN-RESEARCH.md).

## Defects the checks and screenshots found during the build (all fixed)
Hero stage forced the mobile grid wider than the viewport (aspect-ratio + min-height) and clipped text; footer links 21 px tall; `<ol role=tabpanel>` broke list semantics; low-contrast dimmed steps; scrollable regions not keyboard-focusable; SVG `role=img` containing buttons; fixed bottom bar caused a 0.09 layout shift; experience list bullets inheriting a grid rule; a diagram label overlapping its icon.

## Not measured
Interaction to Next Paint (needs real-user or lab interaction traces); real-device touch testing; Safari/Firefox rendering (Chromium only); screen-reader walkthrough with NVDA/VoiceOver; the legacy pages (`projects.html`, `ai-engineering.html`, `nasha-lab.html`) were not restyled and were not part of these runs.
"""
open("docs/redesign/QA-AND-PERFORMANCE.md", "w").write(out)
print("ok")
